#!/usr/bin/env python3
"""
scripts/git/validate_commit.py: Conventional Commit Validator for Kant (kantc).

Strictly enforces Conventional Commits 1.0.0:
- Format: <type>(<scope>): <subject> OR <type>: <subject>
- Allowed types: feat, fix, docs, style, refactor, perf, test, build, ci, chore, revert
- Subject character limit: < 100 characters
- Subject must not end with a period
- Exits 0 on valid commit, 1 on invalid.
"""

import sys
import re
from pathlib import Path
from typing import Tuple, Optional

# Ensure UTF-8 output on Windows consoles
if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass

# Standard conventional commit regex
CONVENTIONAL_REGEX = re.compile(
    r"^(?P<type>feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert)"
    r"(?:\((?P<scope>[a-zA-Z0-9_\-\.\/]+)\))?"
    r"(?P<breaking>!)?"
    r":\s+"
    r"(?P<subject>[^\r\n]+)$"
)

MAX_SUBJECT_LENGTH = 100


def validate_message(raw_msg: str) -> Tuple[bool, Optional[str]]:
    """Validate a commit message string against Conventional Commit invariants."""
    lines = raw_msg.strip().splitlines()
    if not lines:
        return False, "Commit message cannot be empty."

    first_line = lines[0].strip()

    # Allow automated merge commits or squash commits generated by git
    if first_line.startswith("Merge branch") or first_line.startswith("Merge pull request"):
        return True, None

    match = CONVENTIONAL_REGEX.match(first_line)
    if not match:
        return False, (
            f"Commit subject does not conform to Conventional Commits 1.0.0:\n"
            f"  Subject: '{first_line}'\n"
            f"  Expected format: <type>(<scope>): <subject> or <type>: <subject>\n"
            f"  Allowed types: feat, fix, docs, style, refactor, perf, test, build, ci, chore, revert"
        )

    subject = match.group("subject").strip()
    full_header_len = len(first_line)
    if full_header_len > MAX_SUBJECT_LENGTH:
        return False, (
            f"Commit subject header exceeds {MAX_SUBJECT_LENGTH} characters "
            f"(actual length: {full_header_len})."
        )

    if subject.endswith("."):
        return False, "Commit subject should not end with a trailing period."

    if len(lines) > 1 and lines[1].strip() != "":
        return False, "Second line of commit message must be empty (body separation)."

    return True, None


def main() -> int:
    if len(sys.argv) < 2:
        print("Usage: python validate_commit.py <commit_msg_file_or_string>", file=sys.stderr)
        return 1

    arg = sys.argv[1]
    path = Path(arg)

    if path.is_file():
        try:
            content = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            print(f"[!] Error: Commit message file '{path}' is not valid UTF-8.", file=sys.stderr)
            return 1
    else:
        content = arg

    valid, err = validate_message(content)
    if not valid:
        print(f"[x] Conventional Commit Validation Failed:\n{err}", file=sys.stderr)
        return 1

    first_line = content.strip().splitlines()[0]
    print(f"[✓] Conventional commit validated: {first_line[:80]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
